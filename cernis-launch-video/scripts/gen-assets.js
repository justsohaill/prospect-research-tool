// Generates src/assets.js (icons + logos inlined as strings).
// Usage: node scripts/gen-assets.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const nm = path.join(root, 'node_modules');

const LUCIDE = [
  'check', 'arrow-right', 'briefcase', 'search', 'users', 'user-check', 'shield-check',
  'refresh-cw', 'star', 'zap', 'map-pin', 'clock', 'file-text', 'message-circle', 'code',
  'sparkles', 'network', 'badge-check', 'x', 'hash', 'trophy', 'target', 'send',
];
const icons = {};
for (const n of LUCIDE) {
  const svg = fs.readFileSync(path.join(nm, 'lucide-static/icons', n + '.svg'), 'utf8');
  icons[n] = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').trim();
}

const si = require(path.join(nm, 'simple-icons'));
const wf = si.siWellfound.path.split(/(?=M)/); // two dots, then the "w"
const brand = {
  linkedin: `<svg viewBox="0 0 24 24"><path fill="#0A66C2" d="${si.siLinkedin.path}"/></svg>`,
  github: `<svg viewBox="0 0 24 24"><path fill="#181717" d="${si.siGithub.path}"/></svg>`,
  wellfound: `<svg viewBox="0 0 24 24"><path fill="#D9442F" d="${wf[0]}${wf[1]}"/><path fill="#111" d="${wf.slice(2).join('')}"/></svg>`,
};

// Cernis wordmark, taken from cernis.ai. Each letter is wrapped so it can be animated.
const wmSrc = fs.readFileSync(path.join(root, 'src/wordmark.svg'), 'utf8');
const letters = [...wmSrc.matchAll(/<path d="[^"]+" transform="[^"]+"><\/path>/g)].map((m) => m[0]);
if (letters.length !== 6) throw new Error('expected 6 wordmark letters, got ' + letters.length);
const wordmark =
  `<svg viewBox="173 140 2940 811" fill="none" style="overflow:visible;display:block;width:100%">` +
  `<g fill="#5B50E8">${letters.map((l) => `<g class="wl">${l}</g>`).join('')}</g>` +
  `<circle class="wring" cx="2489" cy="235" r="95" fill="none" stroke="#F97066" stroke-width="18" opacity="0"/>` +
  `<g class="wdot"><circle cx="2489" cy="235" r="95" fill="#F97066"/></g></svg>`;

// Cernis icon glyph (the stemless i + coral dot), from cernis.ai/icon.svg. The gradient tile is CSS.
const glyph =
  `<svg viewBox="0 0 1000 1000" style="display:block;width:100%;height:100%">` +
  `<path transform="translate(410.1,748.62) scale(0.62,-0.62)" d="M215 554V0H75V554Z" fill="#fff"/>` +
  `<circle cx="500" cy="310.28" r="58.9" fill="#F97066"/></svg>`;

fs.writeFileSync(
  path.join(root, 'src/assets.js'),
  '// Generated by scripts/gen-assets.js. Do not edit.\nwindow.A = ' +
    JSON.stringify({ icons, brand, wordmark, glyph }, null, 1) + ';\n'
);
console.log('assets written:', Object.keys(icons).length, 'icons,', Object.keys(brand).length, 'brand logos');
